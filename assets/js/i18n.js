let CURRENT_LANG = 'en';

function getLang() { return CURRENT_LANG; }

function setLang(lang) {
  if (!I18N[lang]) return;
  CURRENT_LANG = lang;
  try { localStorage.setItem('8ball-lang', lang); } catch (e) {}
}

function initLang() {
  let lang = 'en';
  try {
    const saved = localStorage.getItem('8ball-lang');
    if (saved && I18N[saved]) lang = saved;
    else if (navigator.language && navigator.language.slice(0, 2) === 'es') lang = 'es';
  } catch (e) {}
  CURRENT_LANG = lang;
}

/** Look up a UI string, falling back to English, then to the key itself.
 *  vars: optional object for {placeholder} interpolation, e.g. t('common.week', { n: 3 }) */
function t(key, vars) {
  const dict = I18N[CURRENT_LANG] || I18N.en;
  let str = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    }
  }
  return str;
}
